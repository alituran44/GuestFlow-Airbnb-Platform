// FILTER BLOG BY CATEGORY CHIP
function filterBlogCategory(cat, btn) {
  document.querySelectorAll('.blog-filter-btn').forEach(b => b.classList.remove('active'));
  if (btn) btn.classList.add('active');
  renderBlogArticlesGrid(cat, document.getElementById('blog-search-input')?.value || '');
}

// SEARCH BLOG INPUT
function handleBlogSearch(query) {
  const activeBtn = document.querySelector('.blog-filter-btn.active');
  const cat = activeBtn ? activeBtn.getAttribute('data-cat') || 'all' : 'all';
  renderBlogArticlesGrid(cat, query);
}

